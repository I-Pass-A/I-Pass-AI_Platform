-- ============================================================
-- 5. AUTOMATIC PROFILE CREATION
-- ============================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    user_role TEXT;
BEGIN

    -- Convert frontend role names to database roles.
    user_role :=
        CASE
            WHEN LOWER(
                COALESCE(
                    NEW.raw_user_meta_data ->> 'role',
                    'student'
                )
            ) IN (
                'admin',
                'administrator',
                'content administrator'
            )
            THEN 'admin'

            WHEN LOWER(
                COALESCE(
                    NEW.raw_user_meta_data ->> 'role',
                    'student'
                )
            ) IN (
                'teacher',
                'educator'
            )
            THEN 'teacher'

            ELSE 'student'
        END;


    INSERT INTO public.profiles (
        id,
        name,
        role,
        grade,
        language
    )
    VALUES (
        NEW.id,

        COALESCE(
            NEW.raw_user_meta_data ->> 'name',
            'New User'
        ),

        user_role,

        NEW.raw_user_meta_data ->> 'grade',

        COALESCE(
            NEW.raw_user_meta_data ->> 'language',
            'English'
        )
    );

    RETURN NEW;

END;
$$;


-- ============================================================
-- 6. CREATE AUTH USER TRIGGER
-- ============================================================

CREATE TRIGGER on_auth_user_created
AFTER INSERT
ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();


