-- ============================================================
-- 9. VECTOR SEARCH FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION public.match_chunks (
    query_embedding VECTOR(1536),
    match_threshold FLOAT,
    match_count INT,
    filter_subject TEXT,
    filter_grade TEXT,
    filter_language TEXT
)
RETURNS TABLE (
    id BIGINT,
    subject TEXT,
    topic TEXT,
    grade TEXT,
    language TEXT,
    source_document TEXT,
    content TEXT,
    similarity FLOAT
)
LANGUAGE plpgsql
AS $$
BEGIN

    RETURN QUERY

    SELECT
        cc.id,
        cc.subject,
        cc.topic,
        cc.grade,
        cc.language,
        cc.source_document,
        cc.content,

        1 - (
            cc.embedding <=> query_embedding
        ) AS similarity

    FROM public.curriculum_chunks cc

    WHERE cc.subject = filter_subject

    AND cc.grade = filter_grade

    AND cc.language = filter_language

    AND cc.embedding IS NOT NULL

    AND 1 - (
        cc.embedding <=> query_embedding
    ) > match_threshold

    ORDER BY
        cc.embedding <=> query_embedding

    LIMIT match_count;

END;
$$;


